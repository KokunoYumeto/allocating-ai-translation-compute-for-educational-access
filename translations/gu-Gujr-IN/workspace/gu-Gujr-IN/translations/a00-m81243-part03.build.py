def translatable(el, kind, value):
    return bool(value and ((kind in ('text', 'tail') and
        re.search('[A-Za-z]', value) and
        (not el.tag.startswith('{' + M + '}') or el.tag == '{' + M + '}mtext' or kind == 'tail'))
        or kind in ('alt', 'aria-label', 'summary')))


