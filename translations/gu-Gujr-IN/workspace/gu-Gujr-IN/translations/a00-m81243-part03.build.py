def contextual_prose(document):
    """Gujarati sentence order without changing the order or tokens of MathML."""
    def el(id_):
        return document.find('.//*[@id="' + id_ + '"]')
    # Source initial 'The periods are...' was split across an indexed term.
    # Every source node remains; no explanatory local note is injected.
    # The 72 caption needs no comparison with 80, unlike the 76 caption.
    caption = el('CNX_BMath_Figure_01_01_020').find('{' + C + '}caption')
    list(caption)[1].tail = ' તેથી '
    # The source term precedes the number; retain it in an introductory phrase.
    p = el('fs-id2966405')
    p.text = 'હવે ફરીથી '
    list(p)[0].tail = ' સમજીએ: સંખ્યા '
